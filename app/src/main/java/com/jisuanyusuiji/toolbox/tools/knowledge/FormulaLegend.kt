    /** 返回该公式的符号说明；没有可靠说明时返回空字符串。 */
    fun of(item: FormulaItem): String {
        if (item.category == "科学常数") return ""
        EXPLICIT[item.name]?.let { return it }
        val expr = item.expression
        val ctx = pickContext(item) ?: return baseLegend(expr)
        val parts = LinkedHashMap<String, String>()

        // 先放复合符号（a_1、S_n 等）
        ctx.special.forEach { (token, text) ->
            if (expr.contains(token)) parts[token] = text
        }
        // 再按出现顺序放单个字母
        symbolsIn(expr).forEach { symbol ->
            if (parts.size >= 8) return@forEach
            val raw = ctx.symbols[symbol] ?: BASE[symbol] ?: return@forEach
            parts.putIfAbsent(symbol, normalize(symbol, raw))
        }
        if (parts.isEmpty()) return baseLegend(expr)
        return parts.values.joinToString("；")
    }

    private fun baseLegend(expr: String): String {
        val parts = LinkedHashMap<String, String>()
        symbolsIn(expr).forEach { symbol ->
            BASE[symbol]?.let { parts.putIfAbsent(symbol, normalize(symbol, it)) }
        }
        return parts.values.joinToString("；")
    }

    /** 词典值有的已带“符号：”，有的只有解释，这里统一成“符号：解释”。 */
    private fun normalize(symbol: String, raw: String): String =
        if (raw.contains('：')) raw else "$symbol：$raw"

    /** 已知函数名会带来 sin 里的 s、i、n 等噪声字母，先去掉。 */
    private val FUNCTION_WORDS = Regex(
        "(arcsin|arccos|arctan|sinh|cosh|tanh|sin|cos|tan|cot|sec|csc|log|ln|lim|exp|max|min|det|rank|grad|div|rot|Res|Re|Im)"
    )

    private fun symbolsIn(expr: String): List<String> {
        val cleaned = expr.replace(FUNCTION_WORDS, " ")
        val out = LinkedHashMap<String, Unit>()
        cleaned.forEach { c ->
            if (isCjkChar(c)) return@forEach
            val isLatin = c in 'a'..'z' || c in 'A'..'Z'
            val isGreek = c in 'α'..'ω' || c in 'Α'..'Ω'
            if (isLatin || isGreek) out.putIfAbsent(c.toString(), Unit)
        }
        return out.keys.toList()
    }

    private fun isCjkChar(c: Char): Boolean {
        val code = c.code
        return code in 0x4E00..0x9FFF || code in 0x3400..0x4DBF || code in 0x3000..0x303F
    }

